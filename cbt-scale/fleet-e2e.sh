#!/usr/bin/env bash
# fleet-e2e.sh — fleet + logical-group model for repeatable backup runs.
# Companion to density-e2e.sh. Instead of per-run pools, a persistent fleet
# (one pool per OS) is created once; each run selects a logical group of VMs
# (new slice or retry of a previous group), resets their backup objects, and
# runs full + incremental backups against just that group.
#
# Usage:
#   # 1. Build/rebuild the fleet (expensive, run rarely):
#   fleet-e2e.sh fleet-setup --rhel N [--rhel-light K] [--windows M]
#   #    --rhel-light = right-sized RHEL 9 (VM_OS=rhel9-light, pool fleet-rhl,
#   #    10Gi root; run `make rhel-light-golden` once first)
#
#   # 1b. Grow the fleet in place (continues numbering, keeps registry/last_run):
#   fleet-e2e.sh fleet-extend --rhel N [--rhel-light K] [--windows M]
#
#   # 2. Per-run (cheap): new group = slice of the fleet
#   fleet-e2e.sh run --os rhel9|rhel9-light|windows --count N [--offset M]
#                  [--windows-count M2] [--wave 25]
#   #    retry a previous group (all, or only failed VMs):
#   fleet-e2e.sh run --retry <group-id> [--only-failed]
#
# State:
#   $SCALE_STATE_DIR/fleet.yaml                      — persistent fleet registry
#   $SCALE_STATE_DIR/groups/<group-id>.yaml          — per-run group manifest with
#                                               per-VM state and results
# Group/run id format: <kind>-<dd-mm-yyyy-HH-MM-SS> (UTC), e.g.
#   rhel-18-11-2026-14-05-33 — easy to identify when it ran.
#
# Backup naming: see cbt-scale/lib-naming.sh (vm-backup-<group-id>-<rid>, rid = VM name
# without the leading `vm-`; run-scoped, no collisions).
# Cleanup: group-scoped reset only (vmbackups, trackers, backup PVCs/PVs of
# the group's VMs); VMs/roots are NEVER touched by a run. Fleet rebuild
# (`fleet-setup`) is the only destructive fleet-level action.
#
# Requirements (validated execution host): oc, jq, KUBECONFIG, run from repo root.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=cbt-scale/lib-naming.sh
source "$ROOT_DIR/cbt-scale/lib-naming.sh"
# Code lives in cbt-scale/ (tracked); runtime state and evidence live in
# SCALE_STATE_DIR (default: <repo>/artifacts, gitignored).
SCALE_STATE_DIR="${SCALE_STATE_DIR:-$ROOT_DIR/artifacts}"; export SCALE_STATE_DIR
cd "$ROOT_DIR"
: "${KUBECONFIG:?export KUBECONFIG=<path to kubeconfig>}"
NAMESPACE="${NAMESPACE:-vm-cbt-demo}"
FLEET="$SCALE_STATE_DIR/fleet.yaml"
GROUPS_DIR="$SCALE_STATE_DIR/groups"
# both OSes back up to the replica-1 scale pool (test data only); set
# WIN_SC=ocs-storagecluster-ceph-rbd for durable (3-copy) windows backups
RHEL_SC="cbt-scale-pool"; WIN_SC="${WIN_SC:-cbt-scale-pool}"
# ROOT_SC: StorageClass for VM ROOT disks at fleet-setup/extend time.
# Default keeps the durable profile (roots on 3-copy ODF). Set
# ROOT_SC=cbt-scale-pool for fully replica-1 fleets (test data only, zero
# durability). Verified 2026-11-19: cross-pool clone from both the
# rhel9-light and windows-server-2022 golden DataSources works.
ROOT_SC="${ROOT_SC:-}"
ROOT_SC_ARG=()
[[ -n "$ROOT_SC" ]] && ROOT_SC_ARG=(ROOT_SC="$ROOT_SC")
WAVE_DEFAULT=25

ts_id(){ date -u +"%d-%m-%Y-%H-%M-%S"; }
die(){ echo "ERROR: $*" >&2; exit 2; }
log(){ printf '%s %s\n' "$(date -u +%H:%M:%S)" "$*"; }

check_sc_exists(){
  oc get sc "$1" >/dev/null 2>&1 || die "StorageClass '$1' not found — see density-e2e.sh preflight fix hint"
}

# ---------- fleet registry helpers (yaml kept simple: one VM per line) ----------
# fleet.yaml format (regenerated by fleet-setup, appended by group runs):
#   vm<TAB>os<TAB>pool<TAB>ready<TAB>last_run
fleet_list(){ [[ -f "$FLEET" ]] || die "no fleet at $FLEET — run 'fleet-e2e.sh fleet-setup' first"; }

fleet_vms(){      # all vm names
  fleet_list; tail -n +2 "$FLEET" | cut -f1
}
fleet_vms_os(){   # $1 = rhel9|windows
  fleet_list; tail -n +2 "$FLEET" | awk -F'\t' -v os="$1" '$2==os{print $1}'
}
fleet_set_last_run(){  # $1 vm  $2 group-id
  local tmp; tmp=$(mktemp)
  { head -1 "$FLEET"; tail -n +2 "$FLEET" | awk -F'\t' -v vm="$1" -v g="$2" \
      '{if ($1==vm) $5=g; print}' OFS='\t'; } > "$tmp" && mv "$tmp" "$FLEET"
}

# ---------- group manifest helpers ----------
# groups/<id>.yaml: one VM per line with tab-separated state:
#   vm<TAB>state<TAB>full_backup<TAB>incr_backup<TAB>result
group_file(){ echo "$GROUPS_DIR/$1.yaml"; }
group_vms(){ tail -n +2 "$(group_file "$1")" | cut -f1; }

group_set(){  # $1 group  $2 vm  $3 field-index(3=state,4=full,5=incr,6=result)  $4 value
  local f tmp; f="$(group_file "$1")"; tmp=$(mktemp)
  { head -1 "$f"; tail -n +2 "$f" | awk -F'\t' -v vm="$2" -v idx="$3" -v val="$4" \
      -v OFS='\t' '{if ($1==vm) $idx=val; print}'; } > "$tmp" && mv "$tmp" "$f"
}

# ---------- group-scoped backup reset (keeps VMs/roots) ----------
reset_group_backups(){  # $1 group  (uses vm list from manifest)
  local g="$1" re; local -a vms
  mapfile -t vms < <(group_vms "$g")
  (( ${#vms[@]} > 0 )) || die "group $g has no VMs in manifest; refusing to reset"
  re="$(scale_group_object_regex "$g" "${vms[@]}")"
  log "RESET: deleting backup objects for group $g (VMs/roots untouched)"
  # `get` (never `delete`) enumerates; only names matching this group's
  # anchored regex are deleted.
  local kind
  for kind in vmbackup vmbackuptracker pvc; do
    oc get "$kind" -n "$NAMESPACE" -o custom-columns=NAME:.metadata.name --no-headers 2>/dev/null \
      | { grep -E "$re" || true; } \
      | xargs -r oc delete "$kind" -n "$NAMESPACE" --wait=false 2>/dev/null || true
  done
  # finalizer force-unstick (known 4-hop chain stall)
  sleep 45
  oc get vmbackup -n "$NAMESPACE" -o custom-columns=NAME:.metadata.name --no-headers 2>/dev/null \
    | { grep -E "$re" || true; } \
    | while read -r vb; do
        oc patch -n "$NAMESPACE" vmbackup "$vb" --type=json \
          -p '[{"op":"remove","path":"/metadata/finalizers"}]' >/dev/null 2>&1 || true
        oc delete -n "$NAMESPACE" vmbackup "$vb" --wait=false >/dev/null 2>&1 || true
      done
  # purge backup PVs (Released/Available only, scoped by reclaim of deleted PVCs)
  sleep 30
  oc get pv -o json | jq -r '.items[]
      | select(.status.phase=="Released" or .status.phase=="Available")
      | select(.spec.claimRef.namespace=="'"$NAMESPACE"'")
      | .metadata.name' \
  | { cat || true; } \
  | while read -r pv; do
      oc patch pv "$pv" --type=json -p '[{"op":"remove","path":"/metadata/finalizers"}]' >/dev/null 2>&1 || true
      oc delete pv "$pv" --wait=false >/dev/null 2>&1 || true
    done
  sleep 15
  local left; left=$(oc get vmbackup,vmbackuptracker -n "$NAMESPACE" -o name 2>/dev/null | grep -c "$g" || true)
  log "RESET: done ($left group objects remain; VMs still present: $(oc get vm -n "$NAMESPACE" --no-headers | wc -l))"
}

# ---------- fleet setup ----------
# pool -> registry os name. Fixed pools: fleet-rhel (rhel9), fleet-rhl
# (rhel9-light, right-sized: 10Gi root; needs `make rhel-light-golden` once),
# fleet-win (windows).
FLEET_REG_JQ='.metadata.labels["virt-cbt-lab/pool"] as $p
  | select($p=="fleet-rhel" or $p=="fleet-rhl" or $p=="fleet-win")
  | [.metadata.name,
     (if $p=="fleet-rhel" then "rhel9" elif $p=="fleet-rhl" then "rhel9-light" else "windows" end),
     $p, (.status.ready // false | tostring), "-"] | @tsv'
pool_vm_count(){ oc get vm -n "$NAMESPACE" -l "virt-cbt-lab/pool=$1" --no-headers 2>/dev/null | wc -l | tr -d ' '; }

# Tolerant readiness gate for a fleet family: pass when at least
# min_frac of the requested VMs are ready (default 0.95). Logs both ways.
fleet_gate_check(){  # $1 os-name $2 pool $3 requested $4 min_frac (0-1)
  local os="$1" pool="$2" want="$3" frac="$4" ready min
  ready=$(oc get vm -n "$NAMESPACE" -l "virt-cbt-lab/pool=$pool" -o json \
    | jq -r '[.items[] | select(.status.ready == true)] | length')
  # bash arithmetic is integer-only; do the float multiply in awk
  min=$(awk -v w="$want" -v f="$frac" 'BEGIN{printf "%d", int(w * f)}')
  if (( ready >= min )); then
    log "FLEET: $os gate PASS — $ready/$want ready (>= ${min})"
    return 0
  fi
  log "FLEET: $os gate FAIL — only $ready/$want ready (needed >= ${min}); see $SCALE_STATE_DIR/fleet-setup-*.log"
  return 1
}

cmd_fleet_setup(){
  local rhel=0 light=0 win=0
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --rhel) rhel="$2"; shift 2 ;;
      --rhel-light) light="$2"; shift 2 ;;
      --windows) win="$2"; shift 2 ;;
      *) die "fleet-setup: unknown arg $1" ;;
    esac
  done
  (( rhel + light + win > 0 )) || die "fleet-setup --rhel N [--rhel-light K] [--windows M] required"
  check_sc_exists "$RHEL_SC"; (( win > 0 )) && check_sc_exists "$WIN_SC"

  # Fleet pools are fixed names; refuse if they already exist (protect fleet)
  local existing
  existing=$(( $(pool_vm_count fleet-rhel) + $(pool_vm_count fleet-rhl) + $(pool_vm_count fleet-win) ))
  (( existing > 0 )) && die "fleet already exists ($existing VMs) — rebuild requires explicit wipe of pools fleet-rhel/fleet-rhl/fleet-win first"

  # Families provision in PARALLEL (a rhel failure must not block windows,
  # seen 2026-11-21: sequential setup aborted on 20 stuck rhel VMs and the
  # windows pool never started). A family that misses the readiness gate is
  # tolerated at FLEET_MIN_READY_FRAC (default 0.95): the run continues
  # with the VMs that are ready and the failure is reported loudly. The
  # readiness wait itself has a repair loop (density_wait_for_ready,
  # density-lib.sh) for PausedIOError boots and stuck CDI clones.
  log "FLEET: creating $rhel rhel9 + $light rhel9-light + $win windows VMs (persistent pools, parallel families)"
  set -a; . ./.env 2>/dev/null || true; set +a
  local min_frac="${FLEET_MIN_READY_FRAC:-0.95}" rpid=0 lpid=0 wpid=0 rc=0
  if (( rhel > 0 )); then
    # VM_OS/POOL are make ARGUMENTS: `.env` (VM_OS=rhel9) overrides env vars in make
    make density-setup VM_OS=rhel9 POOL=fleet-rhel MANIFEST_VARIANT=large-odf "${ROOT_SC_ARG[@]+"${ROOT_SC_ARG[@]}"}" \
      DENSITY_VM_COUNT="$rhel" DENSITY_INCREMENTAL_PASSES=1 DENSITY_QPS=50 \
      DENSITY_WAIT_MINUTES=$(( rhel / 4 + 60 )) > "$SCALE_STATE_DIR/fleet-setup-rhel.log" 2>&1 &
    rpid=$!
  fi
  if (( light > 0 )); then
    make density-setup VM_OS=rhel9-light POOL=fleet-rhl MANIFEST_VARIANT=large-odf "${ROOT_SC_ARG[@]+"${ROOT_SC_ARG[@]}"}" \
      DENSITY_VM_COUNT="$light" DENSITY_INCREMENTAL_PASSES=1 DENSITY_QPS=50 \
      DENSITY_WAIT_MINUTES=$(( light / 4 + 60 )) > "$SCALE_STATE_DIR/fleet-setup-rhl.log" 2>&1 &
    lpid=$!
  fi
  if (( win > 0 )); then
    make density-setup VM_OS=windows POOL=fleet-win GUEST_EXEC_POLL_ATTEMPTS=450 "${ROOT_SC_ARG[@]+"${ROOT_SC_ARG[@]}"}" \
      DENSITY_VM_COUNT="$win" DENSITY_INCREMENTAL_PASSES=1 DENSITY_QPS=50 \
      DENSITY_WAIT_MINUTES=$(( win / 4 + 120 )) > "$SCALE_STATE_DIR/fleet-setup-win.log" 2>&1 &
    wpid=$!
  fi
  # Tolerant gate: wait each family; a family fails the gate only when its
  # ready count is below min_frac of requested.
  if (( rpid > 0 )); then
    wait "$rpid" || true
    fleet_gate_check rhel9 fleet-rhel "$rhel" "$min_frac" || rc=1
  fi
  if (( lpid > 0 )); then
    wait "$lpid" || true
    fleet_gate_check rhel9-light fleet-rhl "$light" "$min_frac" || rc=1
  fi
  if (( wpid > 0 )); then
    wait "$wpid" || true
    fleet_gate_check windows fleet-win "$win" "$min_frac" || rc=1
  fi
  (( rc == 0 )) || log "FLEET: WARNING — one or more families below ${min_frac} ready; see fleet-setup-*.log (fleet usable, run with reduced counts)"
 
  mkdir -p "$(dirname "$FLEET")" "$GROUPS_DIR"
  { printf 'vm\tos\tpool\tready\tlast_run\n'
    oc get vm -n "$NAMESPACE" -o json | jq -r ".items[] | $FLEET_REG_JQ"
  } > "$FLEET"
  log "FLEET: ready — $(wc -l < "$FLEET" | tr -d ' ') registry rows ($(fleet_vms | wc -l) VMs)"
}

# ---------- fleet extend ----------
cmd_fleet_extend(){
  local rhel=0 light=0 win=0
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --rhel) rhel="$2"; shift 2 ;;
      --rhel-light) light="$2"; shift 2 ;;
      --windows) win="$2"; shift 2 ;;
      *) die "fleet-extend: unknown arg $1" ;;
    esac
  done
  (( rhel + light + win > 0 )) || die "fleet-extend --rhel N [--rhel-light K] [--windows M] required"
  fleet_list
  check_sc_exists "$RHEL_SC"; (( win > 0 )) && check_sc_exists "$WIN_SC"
  set -a; . ./.env 2>/dev/null || true; set +a

  local rstart lstart wstart rpid=0 lpid=0 wpid=0
  rstart=$(pool_vm_count fleet-rhel)
  lstart=$(pool_vm_count fleet-rhl)
  wstart=$(pool_vm_count fleet-win)
  (( rstart == $(fleet_vms_os rhel9 | wc -l) && lstart == $(fleet_vms_os rhel9-light | wc -l) && wstart == $(fleet_vms_os windows | wc -l) )) \
    || die "registry ($(fleet_vms_os rhel9 | wc -l)+$(fleet_vms_os rhel9-light | wc -l)+$(fleet_vms_os windows | wc -l)) != cluster ($rstart+$lstart+$wstart) — resolve drift first"

  log "FLEET-EXTEND: +$rhel rhel9 (from $rstart), +$light rhel9-light (from $lstart) and +$win windows (from $wstart), in parallel"
  if (( rhel > 0 )); then
    make density-setup VM_OS=rhel9 POOL=fleet-rhel DENSITY_START_INDEX="$rstart" MANIFEST_VARIANT=large-odf "${ROOT_SC_ARG[@]+"${ROOT_SC_ARG[@]}"}" \
      DENSITY_VM_COUNT="$rhel" DENSITY_INCREMENTAL_PASSES=1 DENSITY_QPS=50 \
      DENSITY_WAIT_MINUTES=$(( rhel / 4 + 60 )) > "$SCALE_STATE_DIR/fleet-extend-rhel.log" 2>&1 &
    rpid=$!
  fi
  if (( light > 0 )); then
    make density-setup VM_OS=rhel9-light POOL=fleet-rhl DENSITY_START_INDEX="$lstart" MANIFEST_VARIANT=large-odf "${ROOT_SC_ARG[@]+"${ROOT_SC_ARG[@]}"}" \
      DENSITY_VM_COUNT="$light" DENSITY_INCREMENTAL_PASSES=1 DENSITY_QPS=50 \
      DENSITY_WAIT_MINUTES=$(( light / 4 + 60 )) > "$SCALE_STATE_DIR/fleet-extend-rhl.log" 2>&1 &
    lpid=$!
  fi
  if (( win > 0 )); then
    make density-setup VM_OS=windows POOL=fleet-win DENSITY_START_INDEX="$wstart" GUEST_EXEC_POLL_ATTEMPTS=450 "${ROOT_SC_ARG[@]+"${ROOT_SC_ARG[@]}"}" \
      DENSITY_VM_COUNT="$win" DENSITY_INCREMENTAL_PASSES=1 DENSITY_QPS=50 \
      DENSITY_WAIT_MINUTES=$(( win / 4 + 120 )) > "$SCALE_STATE_DIR/fleet-extend-win.log" 2>&1 &
    wpid=$!
  fi
  local rc=0
  if (( rpid > 0 )); then wait "$rpid" || { log "rhel extend failed ($SCALE_STATE_DIR/fleet-extend-rhel.log)"; rc=1; }; fi
  if (( lpid > 0 )); then wait "$lpid" || { log "rhel9-light extend failed ($SCALE_STATE_DIR/fleet-extend-rhl.log)"; rc=1; }; fi
  if (( wpid > 0 )); then wait "$wpid" || { log "windows extend failed ($SCALE_STATE_DIR/fleet-extend-win.log)"; rc=1; }; fi

  # append only VMs not yet registered (existing rows keep ready/last_run)
  local known; known=$(fleet_vms)
  oc get vm -n "$NAMESPACE" -o json | jq -r ".items[] | $FLEET_REG_JQ" \
    | sort | while IFS=$'\t' read -r vm rest; do
        grep -qx "$vm" <<<"$known" || printf '%s\t%s\n' "$vm" "$rest"
      done >> "$FLEET"
  log "FLEET-EXTEND: registry now $(fleet_vms_os rhel9 | wc -l) rhel9 + $(fleet_vms_os rhel9-light | wc -l) rhel9-light + $(fleet_vms_os windows | wc -l) windows"
  return "$rc"
}

# ---------- per-run group selection ----------
select_slice(){  # $1 os(rhel9|windows) $2 count $3 offset -> vm names
  fleet_vms_os "$1" | tail -n +"$(( $3 + 1 ))" | head -n "$2"
}

cmd_run(){
  local os="" count="" offset=0 win_count=0 wave="$WAVE_DEFAULT" retry="" only_failed=false
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --os) os="$2"; shift 2 ;;
      --count) count="$2"; shift 2 ;;
      --offset) offset="$2"; shift 2 ;;
      --windows-count) win_count="$2"; shift 2 ;;
      --wave) wave="$2"; shift 2 ;;
      --retry) retry="$2"; shift 2 ;;
      --only-failed) only_failed=true; shift ;;
      *) die "run: unknown arg $1" ;;
    esac
  done

  local group_id vms=() vm
  if [[ -n "$retry" ]]; then
    [[ -f "$(group_file "$retry")" ]] || die "no such group: $retry"
    group_id="${retry}-retry-$(ts_id)"
    if [[ "$only_failed" == true ]]; then
      while IFS=$'\t' read -r vm state _ _ _ result; do
        [[ "$result" == "pass" ]] || vms+=("$vm")
      done < <(tail -n +2 "$(group_file "$retry")")
    else
      mapfile -t vms < <(group_vms "$retry")
    fi
    (( ${#vms[@]} > 0 )) || die "no VMs to retry in $retry"
    log "RUN: retry of $retry (${#vms[@]} VMs) as $group_id"
  else
    [[ -n "$os" && -n "$count" ]] || die "run needs --os <rhel9|rhel9-light|windows> --count N (or --retry <group>)"
    group_id="${os}-$(ts_id)"
    mapfile -t vms < <(select_slice "$os" "$count" "$offset")
    (( ${#vms[@]} == count )) || die "fleet has only ${#vms[@]} $os VMs available at offset $offset (wanted $count) — grow the fleet"
    if (( win_count > 0 )); then
      local wv; mapfile -t wv < <(select_slice windows "$win_count" 0)
      (( ${#wv[@]} == win_count )) || die "fleet has only ${#wv[@]} windows VMs (wanted $win_count)"
      vms+=("${wv[@]}")
    fi
    log "RUN: new group $group_id (${#vms[@]} VMs, os=$os count=$count offset=$offset windows=$win_count)"
  fi

  # health check + write group manifest
  { printf 'vm\tstate\tfull_backup\tincr_backup\tresult\n'
    for vm in "${vms[@]}"; do
      ready=$(oc get vm -n "$NAMESPACE" "$vm" -o jsonpath='{.status.ready}' 2>/dev/null || echo "missing")
      [[ "$ready" == "true" ]] || die "VM $vm not ready/missing — fleet drift; fix or exclude before running"
      printf '%s\tpending\t-\t-\t-\n' "$vm"
    done
  } > "$(group_file "$group_id")"

  reset_group_backups "$group_id"
  # orphan RBD images (PV objects gone, image survived) waste raw capacity — GC them
  bash "$ROOT_DIR/cbt-scale/scale-pool-gc.sh" --delete 2>&1 | sed 's/^/  /' || log "WARN: scale-pool-gc failed (see above)"

  # determine per-OS backup SCs present in this group
  # (capture lists once; `fleet_vms_os | grep -q` under pipefail SIGPIPEs the producer and misclassifies VMs)
  local sc_rhel=false sc_light=false sc_win=false rhel_all light_all win_all os_all
  rhel_all=$(fleet_vms_os rhel9); light_all=$(fleet_vms_os rhel9-light); win_all=$(fleet_vms_os windows)
  for vm in "${vms[@]}"; do
    if grep -qx "$vm" <<<"$rhel_all"; then sc_rhel=true; fi
    if grep -qx "$vm" <<<"$light_all"; then sc_light=true; fi
    if grep -qx "$vm" <<<"$win_all"; then sc_win=true; fi
  done
  bash "$ROOT_DIR/cbt-scale/storage-snapshot.sh" "pre-run-$group_id" 2>&1 | tail -1 || true

  mkdir -p "$SCALE_STATE_DIR/groups/$group_id"
  # per-OS sub-manifests so each driver only drives its own family
  for osf in rhel rhl win; do
    case "$osf" in rhel) os_all=$rhel_all ;; rhl) os_all=$light_all ;; win) os_all=$win_all ;; esac
    { printf 'vm\tstate\tfull_backup\tincr_backup\tresult\n'
      for vm in "${vms[@]}"; do
        if grep -qx "$vm" <<<"$os_all"; then printf '%s\tpending\t-\t-\t-\n' "$vm"; fi
      done
    } > "$SCALE_STATE_DIR/groups/$group_id/$osf.manifest"
  done

  # run driver per OS family against the group (group mode: GROUP_FILE lists
  # the family's VMs; backup objects are named <group-id>-<vm>)
  log "RUN: driving group $group_id (wave $wave)"
  local T0; T0=$(date +%s)
  # PARALLEL_OS=true runs the RHEL, RHEL-light and Windows drivers concurrently (default: sequential)
  local drv_pids=()
  if "$sc_rhel" && (( $(tail -n +2 "$SCALE_STATE_DIR/groups/$group_id/rhel.manifest" | wc -l) > 0 )); then
    GROUP_FILE="$SCALE_STATE_DIR/groups/$group_id/rhel.manifest" GROUP_ID="$group_id" \
      EVIDENCE_DIR="$SCALE_STATE_DIR/groups/$group_id/rhel" BACKUP_SC="$RHEL_SC" \
      bash "$ROOT_DIR/cbt-scale/scale-driver2.sh" > "$SCALE_STATE_DIR/groups/$group_id/driver-rhel.log" 2>&1 \
      || true &
    drv_pids+=($!)
    "${PARALLEL_OS:-false}" || wait "${drv_pids[@]}" || true
  fi
  if "$sc_light" && (( $(tail -n +2 "$SCALE_STATE_DIR/groups/$group_id/rhl.manifest" | wc -l) > 0 )); then
    # right-sized backup PVCs (10Gi root: 12Gi full, 2Gi incremental by default)
    GROUP_FILE="$SCALE_STATE_DIR/groups/$group_id/rhl.manifest" GROUP_ID="$group_id" \
      EVIDENCE_DIR="$SCALE_STATE_DIR/groups/$group_id/rhl" BACKUP_SC="$RHEL_SC" \
      FULL_DEST_SIZE="${RHEL_LIGHT_FULL_BACKUP_SIZE:-12Gi}" INCR_DEST_SIZE="${RHEL_LIGHT_INCREMENTAL_PVC_SIZE:-2Gi}" \
      bash "$ROOT_DIR/cbt-scale/scale-driver2.sh" > "$SCALE_STATE_DIR/groups/$group_id/driver-rhl.log" 2>&1 \
      || true &
    drv_pids+=($!)
    "${PARALLEL_OS:-false}" || wait "${drv_pids[@]}" || true
  fi
  if "$sc_win" && (( $(tail -n +2 "$SCALE_STATE_DIR/groups/$group_id/win.manifest" | wc -l) > 0 )); then
    GROUP_FILE="$SCALE_STATE_DIR/groups/$group_id/win.manifest" GROUP_ID="$group_id" \
      EVIDENCE_DIR="$SCALE_STATE_DIR/groups/$group_id/win" BACKUP_SC="$WIN_SC" \
      bash "$ROOT_DIR/cbt-scale/scale-driver2.sh" > "$SCALE_STATE_DIR/groups/$group_id/driver-win.log" 2>&1 \
      || true &
    drv_pids+=($!)
  fi
  wait "${drv_pids[@]}" 2>/dev/null || true

  local T1=$(( $(date +%s) - T0 ))
  validate_and_summarize "$group_id" "${#vms[@]}" "$T1"
}

validate_and_summarize(){  # $1 group  $2 expected count  $3 wall
  local g="$1" n="$2" wall="$3" vm full incr cp pass fail=0
  for vm in $(group_vms "$g"); do
    full=$(oc get vmbackup -n "$NAMESPACE" "$(scale_full_name "$g" "$vm")" -o jsonpath='{.status.conditions[?(@.type=="Done")].reason}' 2>/dev/null || echo missing)
    incr=$(oc get vmbackup -n "$NAMESPACE" "$(scale_incr_name "$g" "$vm" 1)" -o jsonpath='{.status.conditions[?(@.type=="Done")].reason}' 2>/dev/null || echo missing)
    cp=$(oc get vmbackuptracker -n "$NAMESPACE" "$(scale_tracker_name "$g" "$vm")" -o jsonpath='{.status.latestCheckpoint.name}' 2>/dev/null || echo missing)
    if [[ "$full" == "Successfully completed VirtualMachineBackup" \
       && "$incr" == "Successfully completed VirtualMachineBackup" \
       && "$cp" == "$(scale_incr_name "$g" "$vm" 1)-"* ]]; then
      group_set "$g" "$vm" 3 full_done; group_set "$g" "$vm" 4 "$(scale_full_name "$g" "$vm")"
      group_set "$g" "$vm" 5 "$(scale_incr_name "$g" "$vm" 1)"; group_set "$g" "$vm" 6 pass
    else
      group_set "$g" "$vm" 6 "fail(full=$full,incr=$incr,cp=$cp)"
      fail=$((fail+1))
    fi
    fleet_set_last_run "$vm" "$g"
  done
  bash "$ROOT_DIR/cbt-scale/storage-snapshot.sh" "post-run-$g" 2>&1 | tail -1 || true
  local verdict=PASS; (( fail > 0 )) && verdict=FAIL
  {
    printf 'group: %s\nexpected: %s\nfailed: %s\nverdict: %s\nwall: %ss\n' \
      "$g" "$n" "$fail" "$verdict" "$wall"
    echo "note: verdict from live cluster state (Done reasons + tracker checkpoints)"
  } | tee "$(group_file "$g").summary"
  log "DONE group=$g verdict=$verdict pass=$(( n - fail ))/$n wall=${wall}s"
  [[ "$verdict" == PASS ]]
}

