#!/usr/bin/env bash
set -euo pipefail
# Archive a closed run's local evidence into the gitignored artifacts/ tree.
#
# Usage:
#   scripts/archive-run.sh <run-id> [<run-id> ...]
#   scripts/archive-run.sh --index           regenerate artifacts/INDEX.md only
#
# Chaos runs (cbt-chaos/scenarios_v2/<SCENARIO>/runs/<run-id>) land in
# artifacts/<SCENARIO>/runs/<run-id>; e2e runs (runs/<run-id>) have no
# scenario and land in artifacts/_misc/runs/<run-id>. Only runs whose
# state.json reports phase "closed" (chaos) or whose summary.json reports
# a terminal lifecycle verdict of PASS or FAIL (e2e) are archived;
# in-flight runs are refused so TYPE=incremental adoption (which needs
# runs/<run-id>/run.json in this checkout) keeps working. Moves are
# one-way; nothing is ever copied back.
ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ARTIFACTS_DIR="$ROOT_DIR/artifacts"
SCENARIOS_V2_DIR="$ROOT_DIR/cbt-chaos/scenarios_v2"
RUNS_DIR="$ROOT_DIR/runs"

usage() {
  printf 'Usage: %s <run-id> [<run-id> ...]\n       %s --index\n' "$0" "$0" >&2
  exit 2
}

index_artifacts() {
  local index="$ARTIFACTS_DIR/INDEX.md"
  {
    printf '# AI-generated artifacts index\n\n'
    printf 'Generated by scripts/archive-run.sh --index. Do not edit by hand.\n\n'
    printf 'Layout: one directory per scenario (analysis/, bugs/, followup/,\n'
    printf 'harness-changes/, harness-tickets/, matrix/, runs/) plus _-prefixed\n'
    printf 'categories (_campaign/, _plans/, _validation/, _archive/, _misc/).\n\n'
    printf '## Scenario artifacts\n\n'
    local d
    for d in "$ARTIFACTS_DIR"/*/; do
      local name
      name="$(basename "$d")"
      [[ "$name" == _* ]] && continue
      printf '### %s\n\n' "$name"
      local sub
      for sub in "$d"*/; do
        [[ -d "$sub" ]] || continue
        printf -- '- %s: %s file(s)\n' "$(basename "$sub")" "$(find "$sub" -type f | wc -l | tr -d ' ')"
      done
      printf '\n'
    done
    printf '## Categories\n\n'
    for d in "$ARTIFACTS_DIR"/_*/; do
      [[ -d "$d" ]] || continue
      printf -- '- %s: %s file(s)\n' "$(basename "$d")" "$(find "$d" -type f | wc -l | tr -d ' ')"
    done
  } > "$index"
  printf 'Wrote %s\n' "$index"
}

archive_one() {
  local run_id="$1"
  local src="" scenario="" phase_check=""

  # Chaos run?
  local d
  for d in "$SCENARIOS_V2_DIR"/*/runs/"$run_id"; do
    if [[ -d "$d" ]]; then
      [[ -n "$src" ]] && { printf 'Run %s matches multiple scenarios; refusing.\n' "$run_id" >&2; return 1; }
      src="$d"
      scenario="$(basename "$(dirname "$(dirname "$d")")")"
    fi
  done
  if [[ -n "$src" ]]; then
    local phase
    phase="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1])).get("phase",""))' "$src/state.json" 2>/dev/null || true)"
    if [[ "$phase" != "closed" ]]; then
      printf 'Refusing %s: chaos run phase is %s (not closed).\n' "$run_id" "${phase:-unknown}" >&2
      return 1
    fi
    phase_check="chaos:closed"
  else
    src="$RUNS_DIR/$run_id"
    if [[ ! -d "$src" ]]; then
      printf 'No such run: %s (checked chaos scenario runs/ and runs/).\n' "$run_id" >&2
      return 1
    fi
    # summary.json is written after EVERY stage (including mid-lifecycle
    # TYPE=full/incremental invocations whose verdict is INCOMPLETE), so its
    # existence proves nothing. Require a terminal lifecycle verdict so an
    # unfinished run's run.json stays in runs/ for TYPE=incremental adoption.
    local verdict
    verdict="$(python3 -c 'import json,sys
d = json.load(open(sys.argv[1]))
v = d.get("lifecycle", {}).get("verdict") or d.get("verdict") or ""
print(v)' "$src/summary.json" 2>/dev/null || true)"
    if [[ "$verdict" != "PASS" && "$verdict" != "FAIL" ]]; then
      printf 'Refusing %s: e2e run lifecycle verdict is %s (not PASS/FAIL; still adoptable by TYPE=incremental).\n' \
        "$run_id" "${verdict:-missing}" >&2
      return 1
    fi
    phase_check="e2e:${verdict}"
    scenario="_misc"
  fi

  local dest="$ARTIFACTS_DIR/$scenario/runs/$run_id"
  if [[ -e "$dest" ]]; then
    printf 'Refusing %s: %s already exists.\n' "$run_id" "$dest" >&2
    return 1
  fi
  mkdir -p "$(dirname "$dest")"
  mv "$src" "$dest"
  printf 'Archived %s -> %s (%s)\n' "$run_id" "$dest" "$phase_check"
}

[[ $# -ge 1 ]] || usage
if [[ "$1" == "--index" ]]; then
  [[ $# -eq 1 ]] || usage
  mkdir -p "$ARTIFACTS_DIR"
  index_artifacts
  exit 0
fi

rc=0
for id in "$@"; do
  archive_one "$id" || rc=1
done
mkdir -p "$ARTIFACTS_DIR"
index_artifacts
exit "$rc"
